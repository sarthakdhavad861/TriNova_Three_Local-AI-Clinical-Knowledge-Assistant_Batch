const { chromium } = await import(process.env.PLAYWRIGHT_ENTRY ?? 'playwright')
const URL_ = process.argv[2]
const results = []; const check = (name, ok, extra = '') => { results.push([ok, name, extra]); console.log((ok ? 'PASS ' : 'FAIL ') + name + (ok ? '' : '  ← ' + extra)) }
await fetch(URL_ + '/__reset', { headers: {} }).catch(() => {})
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1500, height: 900 } })
const page = await ctx.newPage()
const errors = []; page.on('pageerror', e => errors.push(String(e))); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto(URL_); await page.waitForSelector('#chat-input')
check('app renders the clinical empty state', (await page.textContent('body')).includes('Clinical reference, from your own documents'))
check('no video/upload/web UI remains', !/video|upload video|web search/i.test(await page.textContent('body')))
// template fills the draft instead of sending
await page.click('text=What is the maximum dose of <medicine name>?')
check('suggestion fills the input (does not send)', (await page.inputValue('#chat-input')).includes('<medicine name>'))
await page.fill('#chat-input', '')
// 1) urgent + unverified answer
await page.fill('#chat-input', 'My patient has chest pain; what is the maximum dose of Fictitrol?'); await page.click('button[aria-label="Send question"]')
await page.waitForSelector('[data-testid="trust"]', { timeout: 15000 })
const alertTxt = await page.textContent('[role="alert"]:has-text("URGENT")')
check('urgent banner shown as role=alert', /URGENT-SYMPTOM KEYWORDS DETECTED/.test(alertTxt ?? ''))
const firstBlock = await page.evaluate(() => { const m = document.querySelector('[data-testid="assistant-message"]'); return m ? [...m.querySelectorAll('[data-testid="notices"],[data-testid="records"],.prose-ai,[data-stub="markdown"]')].map(e => e.dataset.testid || 'answer') : [] })
check('order: notices → records → answer', JSON.stringify(firstBlock.slice(0, 3)) === JSON.stringify(['notices', 'records', 'answer']), JSON.stringify(firstBlock))
const card = await page.textContent('[data-testid="records"]')
check('record card shows verbatim values', card.includes('Maximum 100 mg per day') && card.includes('eGFR < 30 mL/min/1.73m2'), card.slice(0, 200))
check('record card shows warning rows and disclaimer', card.includes('⚠ Contraindications') && card.includes('not a prescription'))
const trust = await page.textContent('[data-testid="trust"]')
check('failed evidence check is shown prominently', /Evidence check failed/.test(trust) && /FAILED/.test(trust) && /999 mg/.test(trust), trust.slice(0, 300))
// 2) sources panel with full text on demand
await page.click('text=/1 source/'); await page.waitForSelector('[data-testid="source-card"]')
await page.click('[data-testid="source-card"] button')
await page.waitForSelector('text=Licence', { timeout: 5000 })
const srcTxt = await page.textContent('[data-testid="source-card"]')
check('source expands to full text + honest provenance ("not recorded" when absent)', srcTxt.includes('maximum dose is 100 mg per day') && srcTxt.includes('not recorded') && srcTxt.includes('v1'), srcTxt.slice(0, 300))
// 3) answered, records-only, abstention
const ask = async (q) => { const before = await page.locator('[data-testid="trust"]').count(); await page.waitForFunction(() => !document.querySelector('button[aria-label="Stop generation"]')); await page.fill('#chat-input', q); await page.click('button[aria-label="Send question"]'); await page.waitForFunction(n => document.querySelectorAll('[data-testid="trust"]').length >= n, before + 1, { timeout: 15000 }); await page.waitForTimeout(150) }
await ask('What is the maximum dose of Fictitrol?')
check('verified answer labelled "Answered from sources"', (await page.locator('[data-testid="trust"]').last().textContent()).includes('Answered from sources'), await page.locator('[data-testid="trust"]').last().textContent())
await ask('Examplometer')
const last = page.locator('[data-testid="assistant-message"]').last()
const lastTxt = await last.textContent()
check('records-only answer says no summary was generated', lastTxt.includes('Structured record only') && lastTxt.includes('Not stated in this record'), lastTxt.slice(0, 300))
await ask('how do I repair a violin')
check('abstention is explicit', (await page.locator('[data-testid="assistant-message"]').last().textContent()).includes('Not in the knowledge base'))
// 4) patient context
await page.click('[role="tab"]:has-text("Patient context")')
await page.fill('#ctx-note', 'synthetic note: renal impairment'); await page.click('button:has-text("Add note")')
await page.waitForSelector('text=synthetic note: renal impairment')
await page.fill('#ctx-note', 'x'.repeat(2001)); await page.click('button:has-text("Add note")')
check('over-long note rejected client-side', await page.locator('text=too long').count() > 0)
// 5) storage hygiene
const ss = await page.evaluate(() => JSON.stringify({ ...sessionStorage })); const ls = await page.evaluate(() => JSON.stringify({ ...localStorage }))
check('sessionStorage holds ids/tokens only (no chat text)', !/chest pain|Fictitrol|renal|dose/i.test(ss) && /token/.test(ss), ss.slice(0, 200))
check('localStorage holds no chat text', !/chest pain|Fictitrol|renal|dose/i.test(ls), ls.slice(0, 200))
// 6) reload: history comes back from the backend (with banner/cards)
await page.reload(); await page.waitForSelector('[data-testid="assistant-message"]', { timeout: 10000 })
const after = await page.textContent('body')
check('after reload history is restored from the backend', after.includes('URGENT-SYMPTOM KEYWORDS DETECTED') && after.includes('Maximum 100 mg per day'))
// 7) knowledge dialog validation
await page.click('button[aria-label="Open knowledge base"]'); await page.waitForSelector('#kb-title')
await page.setInputFiles('input[type=file]', { name: 'a.csv', mimeType: 'text/csv', buffer: Buffer.from('name,dose\nA,1 mg\n') })
await page.click('button:has-text("Add to knowledge base")')
check('upload without licence/origin is blocked', await page.locator('text=Licence is required').count() > 0)
await page.fill('input[placeholder^="e.g."]', 'CC0'); await page.fill('input[placeholder^="URL"]', 'synthetic'); await page.click('button:has-text("Add to knowledge base")')
await page.waitForSelector('text=Indexed.', { timeout: 8000 }); check('upload with provenance succeeds', true)
await page.keyboard.press('Escape')
// 8) erase encounter
// the smoke CSS has no Tailwind (group-hover), so click the (CSS-hidden) button via the DOM
await page.locator('button[aria-label="Erase encounter"]').first().evaluate(el => el.click()); await page.waitForTimeout(200)
await page.locator('button:has-text("Erase"):not([aria-label])').first().evaluate(el => el.click())
await page.waitForFunction(() => !document.querySelector('[data-testid="assistant-message"]'), null, { timeout: 8000 })
const st = await (await fetch(URL_ + '/__state')).json()
check('erase removes the encounter on the backend', Object.keys(st).length === 0, JSON.stringify(st))
check('no uncaught page errors', errors.length === 0, errors.join(' | ').slice(0, 400))
await page.screenshot({ path: process.argv[3] ?? 'smoke.png' })
await browser.close()
const bad = results.filter(r => !r[0]); console.log(`\n${results.length - bad.length}/${results.length} checks passed`); process.exit(bad.length ? 1 : 0)
